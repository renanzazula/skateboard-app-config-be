package com.skateboard.appconfig.domain.model;

/**
 * A predefined type size for a {@link CampaignScreen}'s title or description
 * (spec §7). Predefined steps rather than free-form point sizes keep rendering
 * responsive and on-theme across device sizes.
 */
public enum CampaignTextSize {
    SMALL,
    MEDIUM,
    LARGE,
    EXTRA_LARGE
}
